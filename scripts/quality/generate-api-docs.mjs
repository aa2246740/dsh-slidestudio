import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT } from "./source-files.mjs";
import { apiContracts } from "./api-contracts.mjs";

const checking = process.argv.includes("--check");
let changed = 0;
for (const [name, contract] of Object.entries(apiContracts)) {
  const document = {
    openapi: "3.1.0",
    info: {
      title: contract.title,
      version: "0.2.7",
      description: `Local-first API. Source: ${contract.source}. Critical interfaces only for native/Host; legacy routes are complete. Never expose this loopback-only API publicly.`,
    },
    servers: [
      {
        url: `http://127.0.0.1:${contract.port}`,
        description: "Default local port; isolated checkouts may choose another port.",
      },
    ],
    paths: contract.paths,
  };
  const json = `${JSON.stringify(document, null, 2)}\n`;
  const rows = Object.entries(contract.paths).flatMap(([route, methods]) =>
    Object.entries(methods)
      .filter(([method]) => ["get", "post", "put", "patch", "delete"].includes(method))
      .map(([method, operation]) => `| ${method.toUpperCase()} | \`${route}\` | ${operation.summary} |`),
  );
  const markdown = `# ${contract.title}\n\nGenerated by \`npm run docs:generate\` from \`scripts/quality/api-contracts.mjs\`.\n\nSource: \`${contract.source}\`. This is a local API, not a public cloud endpoint.\n\n| Method | Route | Behavior |\n| --- | --- | --- |\n${rows.join("\n")}\n\nRequest/response fields are in [openapi.json](openapi.json). Native/Host coverage is explicitly limited to these critical interfaces. Provider execution requires user authorization; documentation generation never calls a provider.\n`;
  for (const [filename, content] of [
    ["openapi.json", json],
    ["README.md", markdown],
  ]) {
    const file = path.join(ROOT, "docs/api", name, filename);
    if (checking) {
      if (readFileSync(file, "utf8") !== content) {
        console.error(`Generated API documentation is stale: ${path.relative(ROOT, file)}`);
        changed += 1;
      }
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
  }
}
console.log(`API documentation: ${checking ? `${changed} stale files` : "generated three real service contracts"}`);
process.exitCode = changed ? 1 : 0;
