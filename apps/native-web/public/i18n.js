let active = resolveLang();
const listeners = new Set();

function norm(value) {
  return /^zh/i.test(String(value || "")) ? "zh" : "en";
}

function resolveLang() {
  try {
    const fromUrl = new URLSearchParams(location.search).get("lang");
    if (fromUrl) {
      try { localStorage.setItem("oss.lang", norm(fromUrl)); } catch { /* storage optional */ }
      return norm(fromUrl);
    }
  } catch { /* malformed query — fall through */ }
  try {
    const stored = localStorage.getItem("oss.lang");
    if (stored) return norm(stored);
  } catch { /* storage optional */ }
  if (typeof document === "undefined") return "zh"; // non-browser importers get the product default
  try { return norm(navigator.language); } catch { return "zh"; }
}

/** Current UI language id: "zh" or "en". */
export function lang() {
  return active;
}

/**
 * Translate one Chinese source string. In zh mode the key returns unchanged;
 * in en mode the dictionary hit (or the key itself when untranslated) returns.
 * `{name}` placeholders interpolate from params.
 */
export function t(text, params) {
  let out = active === "en" ? (EN[text] ?? text) : text;
  if (params) out = out.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return out;
}

const I18N_ATTRS = ["title", "placeholder", "aria-label", "value", "alt"];
// `data-i18n-tip` writes the tooltip's `data-tip` attribute (see tooltips.js).
const I18N_DATA_ATTRS = { tip: "data-tip", "agent-prompt": "data-agent-prompt" };

/**
 * Re-render every `data-i18n` element inside root. `data-i18n` carries the
 * Chinese source text; `data-i18n-title` etc. translate attributes the same way.
 */
export function applyI18n(root) {
  const scope = root || document;
  try {
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n") || "");
    });
    for (const attr of I18N_ATTRS) {
      scope.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => {
        const source = el.getAttribute(`data-i18n-${attr}`) || "";
        el.setAttribute(attr, t(source));
      });
    }
    for (const [key, attr] of Object.entries(I18N_DATA_ATTRS)) {
      scope.querySelectorAll(`[data-i18n-${key}]`).forEach((el) => {
        const source = el.getAttribute(`data-i18n-${key}`) || "";
        el.setAttribute(attr, t(source));
      });
    }
    if (scope === document || scope === document.documentElement) {
      document.documentElement.lang = active === "zh" ? "zh-CN" : "en";
      const titleEl = document.querySelector("title[data-i18n]");
      if (titleEl) document.title = t(titleEl.getAttribute("data-i18n") || document.title);
    }
  } catch { /* translation must never break the page */ }
}

/** Subscribe to language switches; returns the unsubscribe. */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function setLang(value) {
  const next = norm(value);
  if (next === active) return;
  active = next;
  applyI18n();
  listeners.forEach((fn) => { try { fn(next) } catch { /* listener bugs must not break i18n */ } });
}

if (typeof window !== "undefined") {
  window.addEventListener("message", (event) => {
    const data = event.data;
    if (data && data.type === "oss:locale" && data.lang) setLang(data.lang);
  });
}

if (typeof document !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyI18n());
  } else {
    applyI18n();
  }
}
